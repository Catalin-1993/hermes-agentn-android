/** The languages the app's language picker offers. */
enum class UiLanguage(
    val tag: String,
    val flag: String,
    val nativeLabel: String,
) {
    ROMANIAN("ro", "🇷🇴", "Română"),
    ENGLISH("en", "🇬🇧", "English"),
    GERMAN("de", "🇩🇪", "Deutsch"),
}

/**
 * Keeps Romanian, which only the shell strings translate, and otherwise normalizes through
 * the legacy catalog. [AppLanguage.fromTag] reads "ro" as English, so older pages fall back
 * to English text while the saved choice stays Romanian.
 */
fun normalizeUiLanguageTag(tag: String?): String {
    val normalized = tag.orEmpty().trim().lowercase()
    return if (normalized == UiLanguage.ROMANIAN.tag || normalized.startsWith("ro-") || normalized.startsWith("ro_")) {
        UiLanguage.ROMANIAN.tag
    } else {
        AppLanguage.fromTag(normalized).tag
    }
}

