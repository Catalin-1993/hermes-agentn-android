fun shellStringsFor(languageTag: String?): ShellStrings = when (normalizeUiLanguageTag(languageTag)) {
    UiLanguage.ROMANIAN.tag -> romanianShellStrings
    UiLanguage.GERMAN.tag -> germanShellStrings
    else -> englishShellStrings
}

val LocalShellStrings = staticCompositionLocalOf { englishShellStrings }
